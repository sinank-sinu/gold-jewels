from odoo import models, api, fields, _
from odoo.exceptions import UserError

class SaleOrder(models.Model):
    _inherit = 'sale.order'

    def action_confirm(self):
        """
        Intercepts order confirmation POST-procurement.
        Let's Odoo generate default records, then cleanly overwrites them.
        """
        # 1. Run core confirmation logic first so Odoo builds the picking documents
        res = super(SaleOrder, self).action_confirm()

        for order in self:
            # Match against your exact tablet layout origin tag (e.g., CART/00011)
            if order.origin and "CART/" in order.origin:
                salesman_tray = order.user_id.salesman_location_id
                if not salesman_tray:
                    raise UserError(_("No Salesman Tray location configured for your user profile."))

                # 2. Iterate over the delivery operations generated by this confirmation
                for picking in order.picking_ids:
                    
                    # Update the top-level Delivery header view field
                    picking.write({
                        'location_id': salesman_tray.id
                    })

                    # 3. Synchronize parent moves (Fixes the Inventory List View layout)
                    for move in picking.move_ids:
                        move.write({
                            'location_id': salesman_tray.id
                        })

                        # 4. Synchronize explicit tracking lines (Fixes Form View & stock reduction)
                        if move.move_line_ids:
                            move.move_line_ids.write({
                                'location_id': salesman_tray.id
                            })
                        else:
                            # Cache-safe fallback loop if record lines haven't fully inflated
                            for line in move.move_line_ids:
                                line.write({
                                    'location_id': salesman_tray.id
                                })
                                
        return res